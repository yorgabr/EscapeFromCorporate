#Requires -Version 5.1
#Requires -Modules @{ ModuleName = 'Pester'; ModuleVersion = '5.5.0' }

# NOTE: these values are computed at SCRIPT scope both here (for Discovery,
# since Pester evaluates -Skip:(...) expressions during that phase) AND again
# inside BeforeAll below (for the Run phase). Pester 6 does not guarantee
# top-level script-scope assignments survive into the separate scope used to
# execute BeforeAll/It during Run - relying on this file's top-level values
# alone caused Import-Module inside BeforeAll to receive $null for -Name.
$script:ModuleRoot   = Join-Path $PSScriptRoot '..\..\src\EscapeFromCorporate'
$script:ManifestPath = Join-Path $script:ModuleRoot 'EscapeFromCorporate.psd1'
$script:MamlPath     = Join-Path $script:ModuleRoot 'en-US\EscapeFromCorporate-help.xml'

BeforeAll {
    # Recompute (idempotent - just path joins) rather than trusting the
    # Discovery-phase values to have survived into this Run-phase scope.
    $script:ModuleRoot   = Join-Path $PSScriptRoot '..\..\src\EscapeFromCorporate'
    $script:ManifestPath = Join-Path $script:ModuleRoot 'EscapeFromCorporate.psd1'
    $script:MamlPath     = Join-Path $script:ModuleRoot 'en-US\EscapeFromCorporate-help.xml'

    Import-Module $script:ManifestPath -Force
}

Describe 'External MAML help' {

    It 'has been generated by the Docs build task' -Skip:(-not (Test-Path $script:MamlPath)) {
        Test-Path $script:MamlPath | Should -BeTrue
    }

    It 'is well-formed XML with the maml command namespace' -Skip:(-not (Test-Path $script:MamlPath)) {
        { [xml](Get-Content -LiteralPath $script:MamlPath -Raw) } | Should -Not -Throw
        $xml = [xml](Get-Content -LiteralPath $script:MamlPath -Raw)
        $xml.helpItems.command.Count | Should -BeGreaterOrEqual 1
    }

    Context 'Get-Help resolves rich content for every public function' {

        $publicFunctions = @('Invoke-EfcJob', 'Get-EfcJobState', 'Resume-EfcJob', 'Clear-EfcState')

        It 'provides a synopsis for <_>' -ForEach $publicFunctions -Skip:(-not (Test-Path $script:MamlPath)) {
            $help = Get-Help -Name $_ -ErrorAction SilentlyContinue
            $help.Synopsis | Should -Not -BeNullOrEmpty
            # The auto-generated stub synopsis equals the syntax line; assert we have real prose.
            $help.Synopsis | Should -Not -Match '^\s*$'
        }

        It 'provides at least one example for <_>' -ForEach @('Invoke-EfcJob', 'Clear-EfcState') `
            -Skip:(-not (Test-Path $script:MamlPath)) {
            $help = Get-Help -Name $_ -Examples -ErrorAction SilentlyContinue
            @($help.Examples.Example).Count | Should -BeGreaterOrEqual 1
        }
    }
}